import streamlit as st
import ollama
from openai import OpenAI
import requests
from typing import Optional, List, Dict, Any, Literal
from pydantic import BaseModel, ValidationError, Field
import time
import re  # Import the regular expression module
import json  # Add json import


class RequestStep(BaseModel):
    timestamp: float = Field(
        ..., description="Unix timestamp when the step was executed", ge=0
    )
    step_name: str = Field(..., description="Name of the processing step", min_length=1)
    model_used: str = Field(
        ..., description="Name/ID of the model used for this step", min_length=1
    )
    input_summary: str = Field(
        ..., description="Summary of the input provided to this step"
    )
    output_summary: str = Field(
        ..., description="Summary of the output generated by this step"
    )
    duration: float = Field(..., description="Duration of the step in seconds", ge=0)

    class Config:
        frozen = True  # Makes the model immutable
        validate_assignment = True  # Validates attribute assignments


class RequestTracker:
    def __init__(self):
        self.steps: List[RequestStep] = []
        self.start_time = time.time()

    def add_step(
        self,
        step_name: str,
        model_used: str,
        input_summary: str,
        output_summary: str,
    ):
        step_time = time.time()
        step = RequestStep(
            timestamp=step_time,
            step_name=step_name,
            model_used=model_used,
            input_summary=input_summary,
            output_summary=output_summary,
            duration=step_time - self.start_time,
        )
        self.steps.append(step)
        return step


# Models for request classification
class RequestType(BaseModel):
    type: Literal["ui_generation", "general_assistance"] = Field(
        ..., description="Type of the request being processed"
    )
    confidence: float = Field(
        ..., description="Confidence score of the classification", ge=0.0, le=1.0
    )
    requires_code: bool = Field(
        ..., description="Whether the request requires code generation"
    )
    description: str = Field(
        ..., description="Detailed description of the request type", min_length=1
    )
    suggested_model: str = Field(
        ..., description="Suggested model for handling this request type", min_length=1
    )

    class Config:
        frozen = True
        validate_assignment = True


class UIComponent(BaseModel):
    name: str = Field(
        ...,
        description="Name of the UI component",
        min_length=1,
        pattern="^[a-zA-Z][a-zA-Z0-9]*$",  # Valid component name pattern
    )
    type: Literal["react", "html", "svg"] = Field(
        ..., description="Type of UI component to generate"
    )
    description: str = Field(
        ...,
        description="Detailed description of the component's purpose and functionality",
        min_length=10,
    )
    complexity: Literal["low", "medium", "high"] = Field(
        ..., description="Estimated complexity level of the component"
    )

    class Config:
        frozen = True
        validate_assignment = True


class ModelCapabilities(BaseModel):
    classification: bool = Field(
        default=False, description="Whether the model supports request classification"
    )
    code_generation: bool = Field(
        default=False, description="Whether the model supports code generation"
    )
    ui_generation: bool = Field(
        default=False, description="Whether the model supports UI component generation"
    )
    analysis: bool = Field(
        default=False, description="Whether the model supports text analysis"
    )
    general_assistance: bool = Field(
        default=False, description="Whether the model supports general assistance tasks"
    )

    class Config:
        frozen = True


class ModelConfig(BaseModel):
    name: str = Field(..., description="Display name of the model", min_length=1)
    provider: Literal["ollama", "openrouter"] = Field(
        ..., description="Provider of the model"
    )
    model_id: str = Field(
        ..., description="Unique identifier for the model", min_length=1
    )
    capabilities: ModelCapabilities = Field(
        default_factory=ModelCapabilities, description="Capabilities of the model"
    )
    context_length: int = Field(
        default=4096, description="Maximum context length in tokens", gt=0
    )
    cost_per_1k_tokens: float = Field(
        default=0.0, description="Cost per 1000 tokens in USD", ge=0.0
    )
    description: str = Field(
        default="", description="Detailed description of the model"
    )
    family: str = Field(default="", description="Model family/architecture")
    parameter_size: str = Field(
        default="", description="Size of the model in parameters"
    )
    quantization_level: str = Field(
        default="", description="Level of model quantization"
    )

    class Config:
        frozen = True
        validate_assignment = True


def debug_model_fetching():
    """Display debug info in an expander."""
    with st.expander("🐛 Debug Information"):
        st.markdown("### Raw Ollama Response")
        try:
            raw_response = ollama.list()
            st.json(raw_response)
        except Exception as e:
            st.error(f"Failed to fetch Ollama models: {str(e)}")

        st.markdown("### Parsed Models (cached)")
        # Now fetch synchronously
        models_data = fetch_available_models()
        st.json(models_data)


@st.cache_data(ttl=300)
def fetch_available_models(openrouter_api_key: str = "") -> Dict[str, Dict[str, Any]]:
    """
    Fetch available models from both Ollama and OpenRouter.
    Pass the OpenRouter API key as an argument to force cache invalidation.
    """
    models_dict = {}

    # Fetch Ollama models
    try:
        response = ollama.list()
        if "models" in response:
            for model_data in response["models"]:
                model_name_match = re.search(r"model='(.*?)'", str(model_data))
                family_match = re.search(r"family='(.*?)'", str(model_data))
                parameter_size_match = re.search(
                    r"parameter_size='(.*?)'", str(model_data)
                )
                quantization_level_match = re.search(
                    r"quantization_level='(.*?)'", str(model_data)
                )

                model_name = (
                    model_name_match.group(1) if model_name_match else "unknown"
                )
                family = family_match.group(1) if family_match else "unknown"
                parameter_size = (
                    parameter_size_match.group(1) if parameter_size_match else "unknown"
                )
                quantization_level = (
                    quantization_level_match.group(1)
                    if quantization_level_match
                    else "unknown"
                )

                capabilities = {
                    "classification": True,
                    "code_generation": "B" in parameter_size
                    and float(parameter_size.replace("B", "").replace(" ", "")) >= 7.0,
                    "ui_generation": "B" in parameter_size
                    and float(parameter_size.replace("B", "").replace(" ", "")) >= 7.0,
                    "analysis": True,
                    "general_assistance": True,
                }
                # Granite special logic
                if "granite" in model_name.lower():
                    if "2b" in model_name.lower():
                        capabilities = {
                            "classification": True,
                            "code_generation": False,
                            "ui_generation": False,
                            "analysis": False,
                            "general_assistance": True,
                        }
                    elif "8b" in model_name.lower():
                        capabilities = {
                            "classification": False,
                            "code_generation": True,
                            "ui_generation": True,
                            "analysis": True,
                            "general_assistance": True,
                        }

                models_dict[f"ollama/{model_name}"] = {
                    "name": model_name,
                    "provider": "ollama",
                    "model_id": model_name,
                    "capabilities": capabilities,
                    "context_length": 32768,
                    "cost_per_1k_tokens": 0.0,  # Ollama models are free
                    "description": f"Family: {family}, Size: {parameter_size}, Quantization: {quantization_level}",
                    "family": family,
                    "parameter_size": parameter_size,
                    "quantization_level": quantization_level,
                }

    except requests.exceptions.ConnectionError as e:
        st.warning(f"Failed to connect to Ollama: {e}")
    except Exception as e:
        st.warning(f"Failed to fetch Ollama models: {e}")

    # Fetch OpenRouter models
    if openrouter_api_key:  # Use the passed-in key
        try:
            response = requests.get(
                "https://openrouter.ai/api/v1/models",
                headers={
                    "Authorization": f"Bearer {openrouter_api_key}",
                    "HTTP-Referer": "localhost:8501",
                    "X-Title": "Unified Chat Router",
                },
            )
            response.raise_for_status()
            data = response.json()
            # The OpenRouter API returns models in a 'data' key
            if isinstance(data, dict) and "data" in data:
                model_list = data["data"]
            else:
                model_list = (
                    data if isinstance(data, list) else []
                )  # Handle unexpected formats

            for model in model_list:
                model_id = model.get("id")
                if not model_id:
                    continue
                context_length = model.get("context_length", 4096)
                pricing = model.get("pricing", {})

                # Ensure cost is non-negative
                try:
                    cost = float(pricing.get("prompt", 0.0))
                    cost = max(0.0, cost)  # Ensure non-negative
                except (ValueError, TypeError):
                    cost = 0.0  # Default to free if invalid cost

                capabilities = {
                    "classification": True,
                    "code_generation": context_length >= 8192,
                    "ui_generation": context_length >= 8192,
                    "analysis": True,
                    "general_assistance": True,
                }

                # Get additional details if available, providing defaults
                family = model.get("family", "Unknown")
                parameter_size = model.get("parameter_size", "Unknown")
                quantization_level = model.get("quantization_level", "Unknown")

                models_dict[f"openrouter/{model_id}"] = {
                    "name": model.get("name", model_id),
                    "provider": "openrouter",
                    "model_id": model_id,
                    "capabilities": capabilities,
                    "context_length": context_length,
                    "cost_per_1k_tokens": cost,
                    "description": model.get("description", ""),
                    "family": family,
                    "parameter_size": parameter_size,
                    "quantization_level": quantization_level,
                }

        except requests.exceptions.RequestException as e:
            st.warning(f"Request to OpenRouter failed: {e}")
        except Exception as e:
            st.warning(f"Failed to fetch OpenRouter models: {e}")

    return models_dict


def initialize_state():
    """Initialize session state variables."""
    if "openrouter_api_key" not in st.session_state:
        st.session_state.openrouter_api_key = ""
    if "classification_model" not in st.session_state:
        st.session_state.classification_model = "ollama/granite3.1-dense:2b"
    if "generation_model" not in st.session_state:
        st.session_state.generation_model = "ollama/granite3.1-dense:8b"
    if "messages" not in st.session_state:
        st.session_state.messages = []


def get_model_client(model_config: ModelConfig):
    """Return appropriate client based on model provider."""
    if model_config.provider == "ollama":
        return ollama
    elif model_config.provider == "openrouter":
        if not st.session_state.openrouter_api_key:
            raise ValueError("OpenRouter API key is required for OpenRouter models")
        return OpenAI(
            base_url="https://openrouter.ai/api/v1",
            api_key=st.session_state.openrouter_api_key,
            default_headers={
                "HTTP-Referer": "localhost:8501",  # Replace with your actual referrer
                "X-Title": "Unified Chat Router",
            },
        )
    else:
        raise ValueError(f"Unknown provider: {model_config.provider}")


def display_response_with_timeline(response: Dict[str, Any]):
    """Display the response along with a timeline of steps."""
    if response["type"] == "error":
        st.error(response["response"])
        return

    st.info(f"Request Type: {response['type']}")
    st.caption(f"Final Model Used: {response['model_used']}")

    st.markdown("### 📊 Request Timeline")
    for step in response["request_timeline"]:
        col1, col2 = st.columns([3, 1])
        with col1:
            st.markdown(f"**{step['step_name']}**")
        with col2:
            st.markdown(f"_{step['duration']:.2f}s_")
        st.markdown(f"Model: `{step['model_used']}`")
        st.markdown("**Input:**")
        st.code(step["input_summary"])
        st.markdown("**Output:**")
        st.code(step["output_summary"])
        st.markdown("---")

    st.markdown("### 💬 Response")
    if response["type"] == "ui_generation":
        with st.expander("Component Details"):
            st.json(response["component_details"])
        st.code(response["response"])
    else:
        st.write(response["response"])


