def route_request(prompt: str, models: Dict[str, ModelConfig]) -> Dict[str, Any]:
    """Route the user's request to the appropriate handler."""
    tracker = RequestTracker()

    try:
        classification_model = models[st.session_state.classification_model]
        classification_client = get_model_client(classification_model)

        system_prompt = """You are a router system that analyzes requests and determines their type.
Return a JSON object with:
- type: either "ui_generation" or "general_assistance"
- confidence: a float between 0.0 and 1.0 (not percentage)
- requires_code: boolean
- description: string describing the request
- suggested_model: string with model name

Example response:
{
    "type": "general_assistance",
    "confidence": 0.95,
    "requires_code": false,
    "description": "General question about programming",
    "suggested_model": "gpt-3.5-turbo"
}"""

        if classification_model.provider == "ollama":
            classification = classification_client.chat(
                model=classification_model.model_id,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": prompt},
                ],
                format=RequestType.model_json_schema(),
                options={"temperature": 0},
            )
            response_content = classification.message.content
        else:
            classification = classification_client.chat.completions.create(
                model=classification_model.model_id,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": prompt},
                ],
                response_format={"type": "json_object"},
                temperature=0,
            )
            response_content = classification.choices[0].message.content

        # Parse the response and ensure confidence is a float between 0 and 1
        response_dict = (
            response_content
            if isinstance(response_content, dict)
            else json.loads(response_content)
        )

        # Convert confidence to float and normalize if it's a percentage
        confidence = float(response_dict["confidence"])
        if confidence > 1:  # If confidence is given as percentage
            confidence = confidence / 100.0
        response_dict["confidence"] = confidence

        request_type = RequestType.model_validate(response_dict)

        tracker.add_step(
            "Classification",
            st.session_state.classification_model,
            f"User prompt: {prompt[:100]}...",
            f"Classification: {request_type.model_dump_json()}",
        )

        generation_model = models[st.session_state.generation_model]
        generation_client = get_model_client(generation_model)

        if request_type.type == "ui_generation":
            component_prompt = """You are using the {model} model to generate UI components...
[Your existing component prompt here]"""  # Removed extra line breaks

            if generation_model.provider == "ollama":
                details_response = generation_client.chat(
                    model=generation_model.model_id,
                    messages=[
                        {"role": "system", "content": component_prompt},
                        {"role": "user", "content": prompt},
                    ],
                    format=UIComponent.model_json_schema(),
                )
                component_details = details_response.message.content
            else:
                details_response = generation_client.chat.completions.create(
                    model=generation_model.model_id,
                    messages=[
                        {"role": "system", "content": component_prompt},
                        {"role": "user", "content": prompt},
                    ],
                    response_format={"type": "json_object"},
                )
                component_details = details_response.choices[0].message.content

            tracker.add_step(
                "Component Analysis",
                st.session_state.generation_model,
                f"Analyzing component requirements for: {prompt[:100]}...",
                f"Component details: {component_details}",
            )

            code_prompt = f"""Generate a complete, working React component that fulfills these requirements:

{prompt}

The component should:
1. Include all necessary imports
2. Use modern React practices (hooks, functional components)
3. Include proper TypeScript/PropTypes if needed
4. Include basic styling
5. Be well-commented
6. Be production-ready

Return only the component code without any explanations."""

            if generation_model.provider == "ollama":
                code_response = generation_client.chat(
                    model=generation_model.model_id,
                    messages=[
                        {
                            "role": "system",
                            "content": "You are an expert React developer. Generate complete, working component code.",
                        },
                        {"role": "user", "content": code_prompt},
                    ],
                )
                generated_code = code_response.message.content
            else:
                code_response = generation_client.chat.completions.create(
                    model=generation_model.model_id,
                    messages=[
                        {
                            "role": "system",
                            "content": "You are an expert React developer. Generate complete, working component code.",
                        },
                        {"role": "user", "content": code_prompt},
                    ],
                )
                generated_code = code_response.choices[0].message.content

            tracker.add_step(
                "Code Generation",
                st.session_state.generation_model,
                "Generating component code...",
                f"Generated code length: {len(generated_code)} characters",
            )

            return {
                "type": "ui_generation",
                "model_used": st.session_state.generation_model,
                "response": generated_code,
                "classification_details": request_type.model_dump(),
                "component_details": component_details,
                "request_timeline": [step.model_dump() for step in tracker.steps],
            }
        else:
            if generation_model.provider == "ollama":
                response = generation_client.chat(
                    model=generation_model.model_id,
                    messages=[{"role": "user", "content": prompt}],
                )
                response_content = response.message.content
            else:
                response = generation_client.chat.completions.create(
                    model=generation_model.model_id,
                    messages=[{"role": "user", "content": prompt}],
                )
                response_content = response.choices[0].message.content

            tracker.add_step(
                "General Response",
                st.session_state.generation_model,
                prompt,
                response_content,
            )

            return {
                "type": "general_assistance",
                "model_used": st.session_state.generation_model,
                "response": response_content,
                "classification_details": request_type.model_dump(),
                "request_timeline": [step.model_dump() for step in tracker.steps],
            }

    except Exception as e:
        tracker.add_step("Error", "N/A", prompt, str(e))
        return {
            "type": "error",
            "error": str(e),
            "response": f"An error occurred: {str(e)}",
            "request_timeline": [step.model_dump() for step in tracker.steps],
        }


def main():
    st.set_page_config(page_title="Unified Chat Router", page_icon="🤖", layout="wide")

    initialize_state()

    st.title("🤖 Unified Chat Router")
    if st.sidebar.checkbox("Show Debug Info"):
        debug_model_fetching()

    # Crucial change: Pass the API key to fetch_available_models
    models_data = fetch_available_models(st.session_state.openrouter_api_key)
    models: Dict[str, ModelConfig] = {
        k: ModelConfig(**v) for k, v in models_data.items()
    }

    display_model_selector(models)

    if st.sidebar.button("🗑️ Clear Chat History"):
        st.session_state.messages = []
        st.rerun()  # Force a re-render

    for message in st.session_state.messages:
        with st.chat_message(message["role"]):
            if message["role"] == "user":
                st.write(message["content"])
            else:
                display_response_with_timeline(message["content"])

    if prompt := st.chat_input("What would you like me to help you with?"):
        st.session_state.messages.append({"role": "user", "content": prompt})
        with st.chat_message("user"):
            st.write(prompt)
        with st.chat_message("assistant"):
            with st.spinner("Thinking..."):
                response = route_request(prompt, models)
                st.session_state.messages.append(
                    {"role": "assistant", "content": response}
                )
                display_response_with_timeline(response)


if __name__ == "__main__":
    main()